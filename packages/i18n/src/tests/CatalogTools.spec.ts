import {after, before, describe, it} from 'node:test'
import assert from 'node:assert'
import {mkdirSync, mkdtempSync, rmSync, writeFileSync} from 'node:fs'
import {tmpdir} from 'node:os'
import path from 'node:path'
import {CheckCatalogs, GenerateMessageTypes, I18nCatalogException, LoadCatalogs, type CatalogIssue, type Catalogs} from '../exports/I18n.js'

describe('The tools of the messages', (): void => {
    let directory: string
    let catalogs: Catalogs

    before(async (): Promise<void> => {
        directory = mkdtempSync(path.join(tmpdir(), 'lakutata-i18n-tools-'))
        writeFileSync(path.join(directory, 'en.json'), JSON.stringify({
            order: {
                count: '{count, plural, one {# order} other {# orders}}',
                created: 'Order created for {customer} at {at, date, short}',
                total: 'Total: {total, number, currency}',
                role: '{role, select, admin {Administrator} other {User}}',
                'final': 'Done'
            },
            app: {name: 'Shop'},
            validation: {any: {required: '{{#label}} is needed'}}
        }))
        writeFileSync(path.join(directory, 'zh-CN.json'), JSON.stringify({
            order: {
                count: '共 # 个订单',
                created: '已为 {customer} 创建订单（{when}）',
                total: '合计：{total, number, currency',
                role: '{role, select, admin {管理员} other {用户}}',
                extra: '多余的消息'
            },
            app: {name: 'Shop'},
            validation: {any: {required: '{{#label}} 为必填项', unknownCode: '{{#label}}'}, string: {min: '{{#label}} 至少 {{#max}} 个字符'}}
        }))
        mkdirSync(path.join(directory, 'zh-TW'))
        writeFileSync(path.join(directory, 'zh-TW', 'order.json'), JSON.stringify({count: '{count, plural, other {共 # 筆訂單}}'}))
        catalogs = await LoadCatalogs([directory])
    })

    after((): void => rmSync(directory, {recursive: true, force: true}))

    it('load the messages of directories', (): void => {
        assert.deepStrictEqual([...catalogs.keys()].sort(), ['en', 'zh-CN', 'zh-TW'])
        assert.strictEqual(catalogs.get('zh-TW')!.get('order.count'), '{count, plural, other {共 # 筆訂單}}')
    })

    it('tell the errors and the warnings of the messages of the languages, against the default language', (): void => {
        const issues: string[] = CheckCatalogs(catalogs, 'en').map((issue: CatalogIssue): string => `${issue.level} ${issue.locale} ${issue.key}: ${issue.message}`)
        assert.deepStrictEqual(issues.filter((issue: string): boolean => issue.startsWith('error')), [
            'error zh-CN order.created: The argument when of the message is not given to the message of en',
            'error zh-CN order.total: zh-CN: order.total: unterminated argument at 4: 合计：{total, number, currency',
            'error zh-CN order.extra: The default language en has no message "order.extra"',
            'error zh-CN validation.any.unknownCode: "any.unknownCode" is not a code of the validation errors',
            'error zh-CN validation.string.min: #max is not a variable of "string.min" (#label, #limit)'
        ])
        assert.deepStrictEqual(issues.filter((issue: string): boolean => issue.startsWith('warning')), [
            'warning zh-CN order.count: The argument count of the message of en is not used',
            'warning zh-CN order.created: The argument at of the message of en is not used',
            'warning zh-CN app.name: The message is the one of en (not translated yet?)',
            'warning zh-CN order.final: The message is missing (the one of a fallback is given)',
            'warning zh-TW order.created: The message is missing (the one of a fallback is given)',
            'warning zh-TW order.total: The message is missing (the one of a fallback is given)',
            'warning zh-TW order.role: The message is missing (the one of a fallback is given)',
            'warning zh-TW order.final: The message is missing (the one of a fallback is given)',
            'warning zh-TW app.name: The message is missing (the one of a fallback is given)'
        ])
        assert.deepStrictEqual(CheckCatalogs(catalogs, 'fr'), [{level: 'error', locale: 'fr', key: '', message: 'There are no messages of the default language fr (en, zh-CN, zh-TW)'}])
    })

    it('generate the declaration of the keys of the default language and of their arguments', (): void => {
        assert.strictEqual(GenerateMessageTypes(catalogs, 'en'), `//Generated by lakutata i18n types from the messages of en: the keys of the messages and their arguments
import 'lakutata/com/i18n'

declare module 'lakutata/com/i18n' {
    interface I18nMessages {
        'app.name': Record<string, never>
        'order.count': { count: number }
        'order.created': { customer: string | number | bigint | boolean | Date, at: Date | number | string }
        'order.final': Record<string, never>
        'order.role': { role: string }
        'order.total': { total: number | bigint, currency?: string }
    }
}
`)
        assert.match(GenerateMessageTypes(catalogs, 'en', '@lakutata/i18n'), /^import '@lakutata\/i18n'\n\ndeclare module '@lakutata\/i18n' \{$/m)
        assert.throws((): unknown => GenerateMessageTypes(catalogs, 'fr'), (error: Error): boolean => error instanceof I18nCatalogException && /no messages of the default language fr/.test(error.message))
    })
})
