//Turn the LDIF of the bundled schema (scripts/schema/source/, written by scripts/schema/generate.mjs from the RFCs, and
//by hand for openssh-lpk and extensions) into the documents of src/lib/schema/bundled/, which the package exports
//(CORE…) and loads without parsing text. The first comment line of each file describes it; the comment before
//each definition (its RFC and section) is kept in the document. Parsed by the engine built (npm run compile first).
//
//   node scripts/schema/documents.mjs
import {readFileSync, writeFileSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'
import {parseSchemaFile} from '../../dist/esm/exports/LDAPEngine.js'

const here = dirname(fileURLToPath(import.meta.url))
const output = join(here, '../../src/lib/schema/bundled')

//The modules: their files (the definitions of the later files added to those of the first), their constants
const MODULES = [
    {name: 'system', files: ['system', 'extensions'], module: 'system', constant: 'SYSTEM'},
    {name: 'core', files: ['core'], module: 'core', constant: 'CORE'},
    {name: 'cosine', files: ['cosine'], module: 'cosine', constant: 'COSINE'},
    {name: 'inetorgperson', files: ['inetorgperson'], module: 'inetorgperson', constant: 'INETORGPERSON'},
    {name: 'rfc2307bis', files: ['rfc2307bis'], module: 'rfc2307bis', constant: 'RFC2307BIS'},
    {name: 'openssh-lpk', files: ['openssh-lpk'], module: 'opensshLpk', constant: 'OPENSSH_LPK'},
    {name: 'ppolicy', files: ['ppolicy'], module: 'ppolicy', constant: 'PPOLICY'}
]

/**
 * A value as TypeScript in the style of the repository: single quotes (double ones for a text with a single quote),
 * no trailing commas, an object or a list on one line when it is short
 */
function literal(value, indent) {
    const pad = '    '.repeat(indent)
    const inner = '    '.repeat(indent + 1)
    if (typeof value === 'string') {
        const escaped = value.replace(/\\/g, '\\\\').replace(/\n/g, '\\n')
        return escaped.includes('\'') && !escaped.includes('"') ? `"${escaped}"` : `'${escaped.replace(/'/g, '\\\'')}'`
    }
    if (typeof value === 'number' || typeof value === 'boolean') return String(value)
    if (Array.isArray(value)) {
        const items = value.map((item) => literal(item, indent + 1))
        const line = `[${items.join(', ')}]`
        return !line.includes('\n') && line.length + indent * 4 < 116 ? line : `[\n${items.map((item) => inner + item).join(',\n')}\n${pad}]`
    }
    const key = (name) => /^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name, 0)
    const fields = Object.entries(value).filter(([, item]) => item !== undefined).map(([name, item]) => `${key(name)}: ${literal(item, indent + 1)}`)
    const line = `{${fields.join(', ')}}`
    return !line.includes('\n') && line.length + indent * 4 < 116 ? line : `{\n${fields.map((field) => inner + field).join(',\n')}\n${pad}}`
}

/**
 * A definition without where it was in its file, only its comment kept
 */
function bare(definition) {
    const {line, span, ...rest} = definition
    void line
    void span
    return rest
}

for (const module of MODULES) {
    const documents = module.files.map((file) => parseSchemaFile(readFileSync(join(here, 'source', `${file}.ldif`), 'utf8'), module.name))
    const description = /^# (.*)$/m.exec(readFileSync(join(here, 'source', `${module.files[0]}.ldif`), 'utf8'))[1]
    const [first, ...rest] = documents
    const document = {
        name: module.name,
        format: 'ldif',
        entry: first.entry,
        attributeTypes: [first, ...rest].flatMap((item) => item.attributeTypes).map(bare),
        objectClasses: [first, ...rest].flatMap((item) => item.objectClasses).map(bare)
    }
    const count = (number, noun) => `${number} ${noun}${number === 1 ? '' : 'es'.slice(noun.endsWith('s') ? 0 : 1)}`
    const counts = `${count(document.attributeTypes.length, 'attribute type')}, ${count(document.objectClasses.length, 'object class')}`
    const source = [
        `//Generated by scripts/schema/documents.mjs from ${module.files.map((file) => `scripts/schema/source/${file}.ldif`).join(' and ')}; do not`,
        '//edit. The definitions are code components of the RFCs named in their comments (see THIRD_PARTY_NOTICES.md).',
        'import type {SchemaDocument} from \'../SchemaDocument.js\'',
        '',
        '/**',
        ` * ${description} (${counts}), as a document`,
        ' * @example',
        ' * ```typescript',
        ' * import {Schema} from \'@lakutata/ldap-engine\'',
        ` * import {${module.constant === 'SYSTEM' ? 'SYSTEM' : `${module.constant}, SYSTEM`}} from '@lakutata/ldap-engine/schemas'`,
        ' *',
        ` * const schema: Schema = new Schema().load(SYSTEM)${module.constant === 'SYSTEM' ? '' : `.load(${module.constant})`}`,
        ` * console.log(${module.constant}.objectClasses.map((objectClass) => objectClass.names[0]), schema.objectClasses().length)`,
        ' * ```',
        ' */',
        `export const ${module.constant}: SchemaDocument = ${literal(document, 0)}`,
        ''
    ].join('\n')
    writeFileSync(join(output, `${module.module}.ts`), source)
    console.log(`${module.name}: ${counts}`)
}
