import {after, before, describe, it} from 'node:test'
import assert from 'node:assert'
import {spawnSync, type SpawnSyncReturns} from 'node:child_process'
import {mkdir, mkdtemp, readdir, readFile, rm, writeFile} from 'node:fs/promises'
import {tmpdir} from 'node:os'
import path from 'node:path'
import {pathToFileURL} from 'node:url'
import {stripVTControlCharacters} from 'node:util'
import ts from 'typescript'
import {Container} from '@lakutata/core'
import {DataSource} from '../../exports/ORM.js'
import {Database} from '../../exports/DatabaseComponent.js'
import {resolveImport} from '../support/ResolveImport.js'

/**
 * The server of the tests (see docker-compose.test.yml), the tests skipped without it
 */
const SERVER: string | undefined = process.env.POSTGRES_URL

/**
 * The columns of the device of the tests, as the applications declare them: a uuid generated by the database
 */
const DEVICE_V1: Record<string, unknown> = {
    id: {type: 'uuid', primary: true, generated: 'uuid'},
    sn: {type: 'varchar', length: 64}
}

/**
 * The device with a new column
 */
const DEVICE_V2: Record<string, unknown> = {...DEVICE_V1, name: {type: 'varchar', length: 128, nullable: true}}

describe('The migrations of a PostgreSQL database', {skip: SERVER ? false : 'POSTGRES_URL is not set'}, (): void => {
    const name: string = `lakutata_migration_${process.pid}_${Date.now()}`
    let admin: DataSource
    let project: string

    before(async (): Promise<void> => {
        admin = new DataSource({type: 'postgres', url: `${SERVER}/postgres`})
        await admin.initialize()
        await admin.query(`CREATE DATABASE "${name}"`)
        project = await mkdtemp(path.join(tmpdir(), 'lakutata-orm-pg-'))
        await writeFile(path.join(project, 'package.json'), JSON.stringify({name: 'project', type: 'module', dependencies: {lakutata: '*'}}))
        await mkdir(path.join(project, 'migrations'))
    })

    after(async (): Promise<void> => {
        await rm(project, {recursive: true, force: true})
        await admin.query(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`)
        await admin.destroy()
    })

    /**
     * The options of the database of the tests
     * @param options
     */
    const options = (options: Record<string, unknown> = {}): Record<string, unknown> => ({type: 'postgres', url: `${SERVER}/${name}`, ...options})

    /**
     * Generate the migration of the device, as `MIGRATION_GENERATE=./migrations` does in a project
     * @param columns
     */
    const generate = (columns: Record<string, unknown>): SpawnSyncReturns<string> => spawnSync(process.execPath, ['--input-type=module', '-e', [
        `import {Application} from '${resolveImport('@lakutata/core')}'`,
        `import {EntitySchema} from '${new URL('../../exports/ORM.js', import.meta.url)}'`,
        `import {buildDatabaseOptions} from '${new URL('../../exports/DatabaseComponent.js', import.meta.url)}'`,
        `const Device = new EntitySchema({name: 'device', columns: ${JSON.stringify(columns)}})`,
        `Application.run({id: 'migration.test', name: 'MigrationTest', components: {db: buildDatabaseOptions({...${JSON.stringify(options())}, entities: [Device]})}})`
    ].join('\n')], {cwd: project, env: {...process.env, MIGRATION_GENERATE: 'migrations'}, encoding: 'utf8', timeout: 60000})

    /**
     * The migrations generated, compiled as the projects compile them (TypeScript to JavaScript), in their order
     */
    const migrations = async (): Promise<Function[]> => {
        const classes: Function[] = []
        for (const file of (await readdir(path.join(project, 'migrations'))).filter((file: string): boolean => file.endsWith('.ts')).sort()) {
            const source: string = await readFile(path.join(project, 'migrations', file), 'utf8')
            const compiled: string = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022}}).outputText
            const output: string = path.join(project, 'migrations', file.replace(/\.ts$/, '.mjs'))
            await writeFile(output, compiled)
            classes.push(...Object.values(await import(pathToFileURL(output).href) as Record<string, Function>))
        }
        return classes
    }

    /**
     * Connect the Database component as the applications do, the migrations run when it connects
     * @param fn
     */
    const connected = async (fn: (database: Database) => Promise<void>): Promise<void> => {
        const container: Container = new Container()
        try {
            await fn(await container.set(Database, {options: options({synchronize: false, migrationsRun: true, migrations: await migrations()})}))
        } finally {
            await container.destroy()
        }
    }

    const columns = async (database: Database): Promise<string[]> => (await database.query<{ column_name: string }[]>('SELECT column_name FROM information_schema.columns WHERE table_name = \'device\' ORDER BY column_name'))
        .map((row: { column_name: string }): string => row.column_name)

    it('generates the migration creating the table, run when the database connects', async (): Promise<void> => {
        const generated: SpawnSyncReturns<string> = generate(DEVICE_V1)
        assert.strictEqual(generated.status, 0, generated.stderr + generated.stdout)
        const [file] = await readdir(path.join(project, 'migrations'))
        assert.match(file, /^\d+-db\.ts$/)
        const migration: string = await readFile(path.join(project, 'migrations', file), 'utf8')
        assert.match(migration, /^import \{ MigrationInterface, QueryRunner \} from "lakutata\/orm";/)
        assert.match(migration, /CREATE TABLE "device"/)
        assert.match(migration, /uuid_generate_v4\(\)/)
        await connected(async (database: Database): Promise<void> => {
            assert.deepStrictEqual(await columns(database), ['id', 'sn'])
            //The uuid generated by the database
            const [row] = await database.query<{ id: string }[]>('INSERT INTO device (sn) VALUES (\'SN-1\') RETURNING id')
            assert.match(row.id, /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/)
            assert.strictEqual(await database.showMigrations(), false)
        })
    })

    it('generates the migration of the changes only, run with the data kept', async (): Promise<void> => {
        const generated: SpawnSyncReturns<string> = generate(DEVICE_V2)
        assert.strictEqual(generated.status, 0, generated.stderr + generated.stdout)
        const files: string[] = (await readdir(path.join(project, 'migrations'))).filter((file: string): boolean => file.endsWith('.ts')).sort()
        assert.strictEqual(files.length, 2)
        const migration: string = await readFile(path.join(project, 'migrations', files[1]), 'utf8')
        assert.match(migration, /ALTER TABLE "device"\s+ADD "name" character varying\(128\)/)
        assert.doesNotMatch(migration, /CREATE TABLE/)
        await connected(async (database: Database): Promise<void> => {
            assert.deepStrictEqual(await columns(database), ['id', 'name', 'sn'])
            assert.deepStrictEqual(await database.query('SELECT sn, name FROM device'), [{sn: 'SN-1', name: null}])
        })
    })

    it('generates nothing when the schema has no changes', async (): Promise<void> => {
        const generated: SpawnSyncReturns<string> = generate(DEVICE_V2)
        assert.notStrictEqual(generated.status, 0)
        assert.strictEqual((await readdir(path.join(project, 'migrations'))).filter((file: string): boolean => file.endsWith('.ts')).length, 2)
    })

    it('reverts the last migration, which is pending again', async (): Promise<void> => {
        await connected(async (database: Database): Promise<void> => {
            await database.undoLastMigration()
            assert.deepStrictEqual(await columns(database), ['id', 'sn'])
            assert.strictEqual(await database.showMigrations(), true)
            assert.deepStrictEqual(await database.query('SELECT sn FROM device'), [{sn: 'SN-1'}])
        })
        //Connected again: the migration reverted runs again
        await connected(async (database: Database): Promise<void> => {
            assert.deepStrictEqual(await columns(database), ['id', 'name', 'sn'])
        })
    })

    it('shows, reverts and runs the migrations with the commands of the application (MIGRATION_SHOW, MIGRATION_REVERT, MIGRATION_RUN)', async (): Promise<void> => {
        await migrations()
        const files: string[] = (await readdir(path.join(project, 'migrations'))).filter((file: string): boolean => file.endsWith('.mjs')).sort()
        /**
         * Start the application with its migrations, with the environment of a command
         * @param env
         */
        const command = (env: Record<string, string>): SpawnSyncReturns<string> => {
            const result: SpawnSyncReturns<string> = spawnSync(process.execPath, ['--input-type=module', '-e', [
                `import {Application} from '${resolveImport('@lakutata/core')}'`,
                `import {buildDatabaseOptions} from '${new URL('../../exports/DatabaseComponent.js', import.meta.url)}'`,
                ...files.map((file: string, index: number): string => `import * as migration${index} from '${pathToFileURL(path.join(project, 'migrations', file)).href}'`),
                `const migrations = [${files.map((_file: string, index: number): string => `...Object.values(migration${index})`).join(', ')}]`,
                `Application.run({id: 'migration.test', name: 'MigrationTest', components: {db: buildDatabaseOptions({...${JSON.stringify(options())}, migrations: migrations})}})`
            ].join('\n')], {cwd: project, env: {...process.env, ...env}, encoding: 'utf8', timeout: 60000})
            return {...result, stdout: stripVTControlCharacters(result.stdout), stderr: stripVTControlCharacters(result.stderr)}
        }
        const shown: SpawnSyncReturns<string> = command({MIGRATION_SHOW: '1'})
        assert.strictEqual(shown.status, 0, shown.stderr)
        assert.match(shown.stdout, /\[db\] \[X\] Migrations\d+\n\[db\] \[X\] Migrations\d+\n\[db\] No pending migration/)
        const reverted: SpawnSyncReturns<string> = command({MIGRATION_REVERT: '1'})
        assert.strictEqual(reverted.status, 0, reverted.stderr)
        assert.match(reverted.stdout, /\[db\] Migration Migrations\d+ has been reverted/)
        const check = async (expected: string[]): Promise<void> => {
            const container: Container = new Container()
            try {
                assert.deepStrictEqual(await columns(await container.set(Database, {options: options()})), expected)
            } finally {
                await container.destroy()
            }
        }
        await check(['id', 'sn'])
        assert.match(command({MIGRATION_SHOW: '1'}).stdout, /\[ \] Migrations\d+\n\[db\] 1 pending migration\n/)
        const ran: SpawnSyncReturns<string> = command({MIGRATION_RUN: '1'})
        assert.strictEqual(ran.status, 0, ran.stderr)
        assert.match(ran.stdout, /\[db\] Migration Migrations\d+ has been run/)
        await check(['id', 'name', 'sn'])
    })
})
