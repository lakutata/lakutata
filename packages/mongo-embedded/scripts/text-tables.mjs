// The tables of the text indexes (native/text/tables.h), from the data of Unicode 8.0 (vendor/ucd, the version of the
// text indexes of MongoDB, version 3) and the stop words (native/text/stopwords): the delimiters of the words (the
// characters of Dash, Hyphen, Pattern_Syntax, Quotation_Mark, Terminal_Punctuation and White_Space, but the apostrophe,
// which MongoDB 8.0 keeps in the words of English: native/text/text.c tells it apart), the case folding (C and S, T for
// Turkish), the characters without their diacritics (a character of Diacritic removed, a character decomposed into a
// letter and diacritics the letter), and the
// stop words of each language, sorted by their bytes.
//
// Run: node scripts/text-tables.mjs
import {readFileSync, writeFileSync} from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (file) => readFileSync(path.join(root, file), 'utf8')

// The languages, in the order of their ids in native/text.c (0: none)
const LANGUAGES = ['danish', 'dutch', 'english', 'finnish', 'french', 'german', 'hungarian', 'italian', 'norwegian', 'portuguese', 'romanian', 'russian', 'spanish', 'swedish', 'turkish']

/**
 * The code points of the properties of PropList.txt
 * @param names
 */
function properties(names) {
    const points = new Set()
    for (const line of read('vendor/ucd/PropList.txt').split('\n')) {
        const [data] = line.split('#')
        const [range, property] = data.split(';').map((part) => part?.trim())
        if (!range || !names.includes(property)) continue
        const [first, last] = range.split('..').map((hex) => parseInt(hex, 16))
        for (let point = first; point <= (last ?? first); point++) points.add(point)
    }
    return points
}

/**
 * Sorted code points as ranges [first, last]
 * @param points
 */
function ranges(points) {
    const sorted = [...points].sort((a, b) => a - b)
    const result = []
    for (const point of sorted) {
        const last = result[result.length - 1]
        if (last && last[1] === point - 1) last[1] = point
        else result.push([point, point])
    }
    return result
}

const delimiters = properties(['Dash', 'Hyphen', 'Pattern_Syntax', 'Quotation_Mark', 'Terminal_Punctuation', 'White_Space'])
delimiters.delete(0x27)
const diacritic = properties(['Diacritic'])

const folding = []
const turkish = []
for (const line of read('vendor/ucd/CaseFolding.txt').split('\n')) {
    const [data] = line.split('#')
    const [code, status, mapping] = data.split(';').map((part) => part?.trim())
    if (!mapping) continue
    if (status === 'C' || status === 'S') folding.push([parseInt(code, 16), parseInt(mapping, 16)])
    if (status === 'T') turkish.push([parseInt(code, 16), parseInt(mapping, 16)])
}
folding.sort((a, b) => a[0] - b[0])
turkish.sort((a, b) => a[0] - b[0])

// The canonical decompositions of UnicodeData.txt (its fifth field, without a tag)
const decompositions = new Map()
for (const line of read('vendor/ucd/UnicodeData.txt').split('\n')) {
    const fields = line.split(';')
    if (fields.length < 6 || !fields[5] || fields[5].startsWith('<')) continue
    decompositions.set(parseInt(fields[0], 16), fields[5].split(' ').map((hex) => parseInt(hex, 16)))
}
const decomposed = (point) => decompositions.has(point) ? decompositions.get(point).flatMap(decomposed) : [point]
const stripped = []
for (const point of diacritic) stripped.push([point, 0])
for (const point of decompositions.keys()) {
    if (diacritic.has(point)) continue
    const kept = decomposed(point).filter((part) => !diacritic.has(part))
    if (kept.length === 1 && kept[0] !== point) stripped.push([point, kept[0]])
}
// Kept as they are, as MongoDB 8.0 keeps them (measured): the capital I with a dot (İ) and the combining Greek
// ypogegrammeni
const KEPT = new Set([0x130, 0x345])
stripped.splice(0, stripped.length, ...stripped.filter(([point]) => !KEPT.has(point)))
stripped.sort((a, b) => a[0] - b[0])

const hex = (value) => `0x${value.toString(16).toUpperCase()}`
// Items in lines of a number of them
const lines = (items, size) => {
    const result = []
    for (let at = 0; at < items.length; at += size) result.push(items.slice(at, at + size).join(', '))
    return result.join(',\n  ')
}
const pairs = (rows) => lines(rows.map(([a, b]) => `{${hex(a)}, ${hex(b)}}`), 8)
const quoted = (word) => `"${[...Buffer.from(word, 'utf8')].map((byte) => byte < 0x80 && byte !== 0x22 && byte !== 0x5C ? String.fromCharCode(byte) : `\\${byte.toString(8).padStart(3, '0')}`).join('')}"`

const stopLists = LANGUAGES.map((language) => {
    const words = read(`native/text/stopwords/${language}.txt`).split('\n').map((word) => word.trim()).filter(Boolean)
    return [...new Set(words)].sort((a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b)))
})

let out = `/* The tables of the text indexes: generated by scripts/text-tables.mjs from vendor/ucd (Unicode 8.0) and
** native/text/stopwords. Do not edit. */

/* The delimiters of the words: ranges of code points */
static const uint32_t kDelimiters[][2] = {
  ${pairs(ranges(delimiters))}
};

/* The case folding (C and S): a code point, its folding */
static const uint32_t kFolding[][2] = {
  ${pairs(folding)}
};

/* The case folding of Turkish (T), before the other one */
static const uint32_t kTurkishFolding[][2] = {
  ${pairs(turkish)}
};

/* The characters without their diacritics: a code point, its letter (0: removed) */
static const uint32_t kStripped[][2] = {
  ${pairs(stripped)}
};

`
stopLists.forEach((words, index) => {
    out += `/* The stop words of ${LANGUAGES[index]} */\nstatic const char *const kStop_${LANGUAGES[index]}[] = {\n  ${lines(words.map(quoted), 8)}\n};\n\n`
})
out += `/* The stop words of each language (by its id, 1 to ${LANGUAGES.length}) */\nstatic const struct {\n  const char *const *words;\n  int count;\n} kStopWords[] = {\n  {0, 0},\n${LANGUAGES.map((language) => `  {kStop_${language}, (int)(sizeof(kStop_${language}) / sizeof(kStop_${language}[0]))}`).join(',\n')}\n};\n`
writeFileSync(path.join(root, 'native/text/tables.h'), out)
console.log(`native/text/tables.h: ${ranges(delimiters).length} ranges of delimiters, ${folding.length} foldings, ${turkish.length} Turkish ones, ${stripped.length} characters stripped, ${stopLists.reduce((sum, words) => sum + words.length, 0)} stop words`)
