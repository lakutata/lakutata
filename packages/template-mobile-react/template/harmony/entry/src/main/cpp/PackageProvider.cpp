#include "RNOH/PackageProvider.h"
#include "RNOHPackagesFactory.h"
#include "generated/RNOHGeneratedPackage.h"
#include "NodeHostTurboModule.h"

using namespace rnoh;

// The TurboModule of the Node.js of the application, a C++ one
class NodeHostFactoryDelegate : public TurboModuleFactoryDelegate {
 public:
  SharedTurboModule createTurboModule(Context ctx, const std::string &name) const override {
    if (name == lakutata::NodeHostTurboModule::kModuleName) return std::make_shared<lakutata::NodeHostTurboModule>(ctx.jsInvoker);
    return nullptr;
  }
};

class NodeHostPackage : public Package {
 public:
  NodeHostPackage(Package::Context ctx) : Package(ctx) {}
  std::unique_ptr<TurboModuleFactoryDelegate> createTurboModuleFactoryDelegate() override {
    return std::make_unique<NodeHostFactoryDelegate>();
  }
};

std::vector<std::shared_ptr<Package>> PackageProvider::getPackages(
    Package::Context ctx) {
  auto packages = createRNOHPackages(ctx); // <= autolinking
  packages.push_back(std::make_shared<RNOHGeneratedPackage>(
      ctx)); // generated by codegen-harmony v1 on app preBuilt stage)
  packages.push_back(std::make_shared<NodeHostPackage>(ctx));
  return packages;
}